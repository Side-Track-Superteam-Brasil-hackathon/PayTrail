import { useCallback, useEffect, useRef, useState } from 'react';
import type { FormEvent, KeyboardEvent } from 'react';
import { Link, useParams } from 'react-router-dom';
import { api } from '../../api/client';
import type { Conversation, Message, Proposal } from '../../api/types';
import { useAuth } from '../../auth/AuthContext';
import { errorMessage } from './errors';
import { ProposalCard } from './ProposalCard';
import { defaultPeriod, formatDateTime } from './time';
import { usePolling } from './usePolling';
import './market.css';

function lastCreatedAt(msgs: Message[]): string | undefined {
  let last: string | undefined;
  for (const m of msgs) if (m.createdAt && (!last || m.createdAt > last)) last = m.createdAt;
  return last;
}

function mergeMessages(prev: Message[], incoming: Message[]): Message[] {
  const byId = new Map<string, Message>();
  for (const m of prev) if (m.id) byId.set(m.id, m);
  for (const m of incoming) if (m.id) byId.set(m.id, { ...byId.get(m.id), ...m });
  return [...byId.values()].sort((a, b) => (a.createdAt ?? '').localeCompare(b.createdAt ?? ''));
}

export function ConversationPage() {
  const { conversationId = '' } = useParams();
  const { user } = useAuth();
  const [other, setOther] = useState<Conversation['other']>();
  const [messages, setMessages] = useState<Message[]>([]);
  const [error, setError] = useState<string | null>(null);
  const [text, setText] = useState('');
  const [sending, setSending] = useState(false);
  const [showForm, setShowForm] = useState(false);
  const threadRef = useRef<HTMLDivElement>(null);
  const stickRef = useRef(true);
  const lastRef = useRef<string | undefined>(undefined);
  const inFlight = useRef(false);

  // reset when switching conversations
  useEffect(() => {
    setMessages([]);
    setError(null);
    lastRef.current = undefined;
    stickRef.current = true;
  }, [conversationId]);

  // header: the other participant (from the conversations list)
  useEffect(() => {
    let cancelled = false;
    api<Conversation[]>('/conversations')
      .then((list) => {
        if (!cancelled) setOther(list.find((c) => c.id === conversationId)?.other);
      })
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, [conversationId]);

  const poll = useCallback(async () => {
    if (!conversationId || inFlight.current) return;
    inFlight.current = true;
    try {
      const after = lastRef.current;
      const qs = after ? `?after=${encodeURIComponent(after)}` : '';
      const incoming = await api<Message[]>(`/conversations/${conversationId}/messages${qs}`);
      if (incoming.length > 0) {
        setMessages((prev) => {
          const merged = mergeMessages(prev, incoming);
          lastRef.current = lastCreatedAt(merged);
          return merged;
        });
      }
      setError(null);
    } catch (e) {
      setError(errorMessage(e));
    } finally {
      inFlight.current = false;
    }
  }, [conversationId]);

  usePolling(poll, 3000);

  useEffect(() => {
    const el = threadRef.current;
    if (el && stickRef.current) el.scrollTop = el.scrollHeight;
  }, [messages]);

  function onScroll() {
    const el = threadRef.current;
    if (el) stickRef.current = el.scrollHeight - el.scrollTop - el.clientHeight < 80;
  }

  async function send() {
    const body = text.trim();
    if (!body || sending) return;
    setSending(true);
    try {
      const m = await api<Message>(`/conversations/${conversationId}/messages`, {
        method: 'POST',
        body: JSON.stringify({ body }),
      });
      setText('');
      stickRef.current = true;
      setMessages((prev) => {
        const merged = mergeMessages(prev, [m]);
        lastRef.current = lastCreatedAt(merged);
        return merged;
      });
      setError(null);
    } catch (e) {
      setError(errorMessage(e));
    } finally {
      setSending(false);
    }
  }

  function onKeyDown(e: KeyboardEvent<HTMLTextAreaElement>) {
    if (e.key === 'Enter' && !e.shiftKey && !e.nativeEvent.isComposing) {
      e.preventDefault();
      void send();
    }
  }

  function onProposalChange(p: Proposal) {
    setMessages((prev) => prev.map((m) => (m.proposal?.id === p.id ? { ...m, proposal: p } : m)));
    // pick up the SYSTEM message generated by the decision
    void poll();
  }

  function onProposalCreated() {
    setShowForm(false);
    stickRef.current = true;
    void poll();
  }

  const myId = user?.id;
  const canPropose = !!user && !!other?.role && other.role !== user.role;

  return (
    <div className="market conv">
      <div className="conv-head">
        <Link to="/inbox" className="muted">&larr; Inbox</Link>
        <div>
          <strong>{other?.name ?? 'Conversation'}</strong>{' '}
          {other?.role && <span className="role-tag">{other.role.toLowerCase()}</span>}
        </div>
        <span className="spacer" />
        {canPropose && !showForm && (
          <button className="secondary" onClick={() => setShowForm(true)}>Send proposal</button>
        )}
      </div>

      {showForm && (
        <ProposalForm conversationId={conversationId} onCancel={() => setShowForm(false)} onCreated={onProposalCreated} />
      )}

      <div className="thread" ref={threadRef} onScroll={onScroll}>
        {messages.length === 0 && !error && <p className="muted notice">No messages yet. Say hello.</p>}
        {messages.map((m) => {
          if (m.type === 'SYSTEM') {
            return <div className="notice" key={m.id}>{m.body}</div>;
          }
          if (m.type === 'PROPOSAL' && m.proposal && myId) {
            return <ProposalCard key={m.id} proposal={m.proposal} currentUserId={myId} onChange={onProposalChange} />;
          }
          const mine = m.senderId === myId;
          return (
            <div className={`bubble${mine ? ' mine' : ''}`} key={m.id}>
              {m.body}
              {m.createdAt && <time dateTime={m.createdAt}>{formatDateTime(m.createdAt)}</time>}
            </div>
          );
        })}
      </div>
      {error && <p className="error small">{error}</p>}
      <div className="composer">
        <textarea
          rows={2}
          value={text}
          maxLength={4000}
          placeholder="Write a message (Enter to send, Shift+Enter for a new line)"
          onChange={(e) => setText(e.target.value)}
          onKeyDown={onKeyDown}
          aria-label="Message"
        />
        <button disabled={sending || !text.trim()} onClick={() => void send()}>Send</button>
      </div>
    </div>
  );
}

interface FormProps {
  conversationId: string;
  onCancel: () => void;
  onCreated: () => void;
}

function ProposalForm({ conversationId, onCancel, onCreated }: FormProps) {
  const initial = defaultPeriod();
  const [fee, setFee] = useState('');
  const [currency, setCurrency] = useState<'BRL' | 'USDC'>('BRL');
  const [start, setStart] = useState(initial.start);
  const [end, setEnd] = useState(initial.end);
  const [note, setNote] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function submit(e: FormEvent) {
    e.preventDefault();
    if (end < start) {
      setError('The period end must be after the start.');
      return;
    }
    setBusy(true);
    setError(null);
    try {
      await api<Proposal>(`/conversations/${conversationId}/proposals`, {
        method: 'POST',
        body: JSON.stringify({
          feeAmount: fee.trim(),
          feeCurrency: currency,
          periodStart: start,
          periodEnd: end,
          ...(note.trim() ? { note: note.trim() } : {}),
        }),
      });
      onCreated();
    } catch (err) {
      setError(errorMessage(err));
      setBusy(false);
    }
  }

  return (
    <form className="proposal-form" onSubmit={(e) => void submit(e)}>
      <label>
        Fee amount
        <input
          required
          inputMode="decimal"
          pattern="[0-9]+([.][0-9]{1,6})?"
          placeholder="150.00"
          value={fee}
          onChange={(e) => setFee(e.target.value)}
        />
      </label>
      <label>
        Currency
        <select value={currency} onChange={(e) => setCurrency(e.target.value as 'BRL' | 'USDC')}>
          <option value="BRL">BRL</option>
          <option value="USDC">USDC</option>
        </select>
      </label>
      <label>
        Data access from
        <input type="date" required value={start} onChange={(e) => setStart(e.target.value)} />
      </label>
      <label>
        Data access until
        <input type="date" required value={end} onChange={(e) => setEnd(e.target.value)} />
      </label>
      <label className="full">
        Note
        <textarea rows={2} value={note} onChange={(e) => setNote(e.target.value)} />
      </label>
      {error && <p className="error small full">{error}</p>}
      <div className="btns full">
        <button disabled={busy}>{busy ? 'Sending...' : 'Send proposal'}</button>
        <button type="button" className="secondary" onClick={onCancel}>Cancel</button>
      </div>
    </form>
  );
}
