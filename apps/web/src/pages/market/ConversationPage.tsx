function lastCreatedAt(msgs: Message[]): string | undefined {
  let last: string | undefined;
  for (const m of msgs) if (m.createdAt && (!last || m.createdAt > last)) last = m.createdAt;
  return last;
}

function mergeMessages(prev: Message[], incoming: Message[]): Message[] {
  const byId = new Map<string, Message>();
  for (const m of prev) if (m.id) byId.set(m.id, m);
  for (const m of incoming) if (m.id) byId.set(m.id, { ...byId.get(m.id), ...m });
  return [...byId.values()].sort((a, b) => (a.createdAt ?? '').localeCompare(b.createdAt ?? ''));
}

function Time({ iso, mine }: { iso?: string; mine: boolean }) {
  useI18n(); // re-render on language change
  if (!iso) return null;
  return (
    <time dateTime={iso} className={cx('text-xs text-slate-400 mt-1', mine ? 'mr-1' : 'ml-1')}>
      {formatMessageTime(iso)}
    </time>
  );
}

export function ConversationPage() {
  const { conversationId = '' } = useParams();
  const { user } = useAuth();
  const { t } = useI18n();
  const [other, setOther] = useState<Conversation['other']>();
  const [messages, setMessages] = useState<Message[]>([]);
  const [error, setError] = useState<string | null>(null);
  const [text, setText] = useState('');
  const [sending, setSending] = useState(false);
  const [showForm, setShowForm] = useState(false);
  const threadRef = useRef<HTMLDivElement>(null);
  const stickRef = useRef(true);
  const lastRef = useRef<string | undefined>(undefined);
  const inFlight = useRef(false);

  // reset when switching conversations
  useEffect(() => {
    setMessages([]);
    setError(null);
    lastRef.current = undefined;
    stickRef.current = true;
  }, [conversationId]);

  // header: the other participant (from the conversations list)
  useEffect(() => {
    let cancelled = false;
    api<Conversation[]>('/conversations')
      .then((list) => {
        if (!cancelled) setOther(list.find((c) => c.id === conversationId)?.other);
      })
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, [conversationId]);

  const poll = useCallback(async () => {
    if (!conversationId || inFlight.current) return;
    inFlight.current = true;
    try {
      const after = lastRef.current;
      const qs = after ? `?after=${encodeURIComponent(after)}` : '';
      const incoming = await api<Message[]>(`/conversations/${conversationId}/messages${qs}`);
      if (incoming.length > 0) {
        setMessages((prev) => {
          const merged = mergeMessages(prev, incoming);
          lastRef.current = lastCreatedAt(merged);
          return merged;
        });
      }
      setError(null);
    } catch (e) {
      setError(errorMessage(e));
    } finally {
      inFlight.current = false;
    }
  }, [conversationId]);

  usePolling(poll, 3000);

  useEffect(() => {
    const el = threadRef.current;
    if (el && stickRef.current) el.scrollTop = el.scrollHeight;
  }, [messages]);

  function onScroll() {
    const el = threadRef.current;
    if (el) stickRef.current = el.scrollHeight - el.scrollTop - el.clientHeight < 80;
  }

  async function send() {
    const body = text.trim();
    if (!body || sending) return;
    setSending(true);
    try {
      const m = await api<Message>(`/conversations/${conversationId}/messages`, {
        method: 'POST',
        body: JSON.stringify({ body }),
      });
      setText('');
      stickRef.current = true;
      setMessages((prev) => {
        const merged = mergeMessages(prev, [m]);
        lastRef.current = lastCreatedAt(merged);
        return merged;
      });
      setError(null);
    } catch (e) {
      setError(errorMessage(e));
    } finally {
      setSending(false);
    }
  }

  function onKeyDown(e: KeyboardEvent<HTMLTextAreaElement>) {
    if (e.key === 'Enter' && !e.shiftKey && !e.nativeEvent.isComposing) {
      e.preventDefault();
      void send();
    }
  }

  function onProposalChange(p: Proposal) {
    setMessages((prev) => prev.map((m) => (m.proposal?.id === p.id ? { ...m, proposal: p } : m)));
    // pick up the SYSTEM message generated by the decision
    void poll();
  }

  function onProposalCreated() {
    setShowForm(false);
    stickRef.current = true;
    void poll();
  }

  const myId = user?.id;
  const canPropose = !!user && !!other?.role && other.role !== user.role;
  const otherIsAccountant = other?.role === 'ACCOUNTANT';

  return (
    <ChatLayout activeId={conversationId}>
      {/* Header */}
      <div className="p-3 sm:p-4 border-b border-slate-200 flex items-center gap-3 bg-white">
        <Link
          to="/inbox"
          className="md:hidden p-1.5 -ml-1 rounded-lg text-slate-500 hover:text-slate-900 hover:bg-slate-100"
          aria-label={t('market.conversation.backToInbox')}
        >
          <ArrowLeft size={20} />
        </Link>
        <Avatar name={other?.name} seed={other?.id} />
        <div className="min-w-0 flex-1">
          <h3 className="font-semibold text-slate-900 truncate">{other?.name ?? t('market.conversation.fallbackTitle')}</h3>
          {other?.role && (
            <p className={cx('text-xs font-medium', otherIsAccountant ? 'text-emerald-600' : 'text-indigo-600')}>
              {otherIsAccountant ? t('common.accountant') : t('common.freelancer')}
            </p>
          )}
        </div>
        {canPropose && !showForm && (
          <Button
            variant="secondary"
            size="sm"
            onClick={() => setShowForm(true)}
            icon={<FileSignature size={16} />}
          >
            <span className="hidden sm:inline">{t('market.conversation.sendProposal')}</span>
            <span className="sm:hidden">{t('market.conversation.propose')}</span>
          </Button>
        )}
      </div>

      {showForm && (
        <ProposalForm conversationId={conversationId} onCancel={() => setShowForm(false)} onCreated={onProposalCreated} />
      )}

      {/* Thread */}
      <div
        className="flex-1 overflow-y-auto p-4 sm:p-6 space-y-5 bg-slate-50/50"
        ref={threadRef}
        onScroll={onScroll}
      >
        {messages.length === 0 && !error && (
          <div className="flex justify-center">
            <div className="bg-slate-100 px-4 py-2 rounded-full text-xs font-medium text-slate-500">{t('market.conversation.empty')}</div>
          </div>
        )}
        {messages.map((m) => {
          if (m.type === 'SYSTEM') {
            return (
              <div className="flex justify-center" key={m.id}>
                <div className="bg-slate-100 px-4 py-2 rounded-2xl sm:rounded-full text-xs font-medium text-slate-500 flex items-center gap-2 max-w-[90%] text-center">
                  <ShieldCheck size={14} className="text-emerald-500 shrink-0" />
                  <span>{m.body}</span>
                </div>
              </div>
            );
          }
          if (m.type === 'PROPOSAL' && m.proposal && myId) {
            const mine = m.proposal.senderId === myId;
            return (
              <div key={m.id} className={cx('flex flex-col', mine ? 'items-end' : 'items-start')}>
                <ProposalCard proposal={m.proposal} currentUserId={myId} onChange={onProposalChange} />
                <Time iso={m.createdAt} mine={mine} />
              </div>
            );
          }
          const mine = m.senderId === myId;
          return (
            <div key={m.id} className={cx('flex flex-col', mine ? 'items-end' : 'items-start')}>
              <div
                className={cx(
                  'px-4 py-2.5 rounded-2xl shadow-sm max-w-[85%] sm:max-w-[75%] whitespace-pre-wrap [overflow-wrap:anywhere]',
                  mine
                    ? 'bg-indigo-600 text-[#1b100b] rounded-tr-sm'
                    : 'bg-white border border-slate-200 text-slate-700 rounded-tl-sm',
                )}
              >
                {m.body}
              </div>
              <Time iso={m.createdAt} mine={mine} />
            </div>
          );
        })}
      </div>

      {error && <p className="px-4 pt-2 text-sm text-red-600 bg-white">{error}</p>}

      {/* Composer */}
      <div className="p-3 sm:p-4 border-t border-slate-200 bg-white">
        <div className="flex gap-2 items-end">
          <textarea
            rows={1}
            value={text}
            maxLength={4000}
            placeholder={t('market.conversation.placeholder')}
            onChange={(e) => setText(e.target.value)}
            onKeyDown={onKeyDown}
            aria-label={t('market.conversation.messageLabel')}
            className="flex-1 min-w-0 resize-none max-h-32 bg-slate-50 border border-slate-200 rounded-xl px-4 py-2.5 outline-none focus:ring-2 focus:ring-indigo-500 transition-all placeholder:text-slate-400 placeholder:truncate"
          />
          <button
            type="button"
            disabled={sending || !text.trim()}
            onClick={() => void send()}
            aria-label={t('market.conversation.send')}
            className="bg-indigo-600 hover:bg-indigo-700 text-[#1b100b] p-3 rounded-xl transition-colors disabled:opacity-50 disabled:cursor-not-allowed shrink-0"
          >
            <Send size={20} />
          </button>
        </div>
      </div>
    </ChatLayout>
  );
}

interface FormProps {
  conversationId: string;
  onCancel: () => void;
  onCreated: () => void;
}

function ProposalForm({ conversationId, onCancel, onCreated }: FormProps) {
  const { t } = useI18n();
  const initial = defaultPeriod();
  const [fee, setFee] = useState('');
  const [currency, setCurrency] = useState<'BRL' | 'USDC'>('BRL');
  const [start, setStart] = useState(initial.start);
  const [end, setEnd] = useState(initial.end);
  const [note, setNote] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function submit(e: FormEvent) {
    e.preventDefault();
    if (end < start) {
      setError(t('market.proposalForm.periodInvalid'));
      return;
    }
    setBusy(true);
    setError(null);
    try {
      await api<Proposal>(`/conversations/${conversationId}/proposals`, {
        method: 'POST',
        body: JSON.stringify({
          feeAmount: fee.trim(),
          feeCurrency: currency,
          periodStart: start,
          periodEnd: end,
          ...(note.trim() ? { note: note.trim() } : {}),
        }),
      });
      onCreated();
    } catch (err) {
      setError(errorMessage(err));
      setBusy(false);
    }
  }

  return (
    <form
      className="border-b border-slate-200 bg-white p-4 max-h-[55%] overflow-y-auto shrink-0"
      onSubmit={(e) => void submit(e)}
    >
      <div className="flex items-center justify-between mb-3">
        <h4 className="flex items-center gap-2 font-semibold text-slate-900">
          <ShieldCheck size={18} className="text-indigo-600" /> {t('market.proposalForm.title')}
        </h4>
        <button type="button" onClick={onCancel} aria-label={t('common.close')} className="p-1 rounded-lg text-slate-400 hover:text-slate-700 hover:bg-slate-100">
          <X size={18} />
        </button>
      </div>
      <div className="grid sm:grid-cols-2 gap-3">
        <Field label={t('market.proposalForm.feeAmount')}>
          <input
            required
            inputMode="decimal"
            pattern="[0-9]+([.][0-9]{1,6})?"
            placeholder="150.00"
            value={fee}
            onChange={(e) => setFee(e.target.value)}
            className={`${inputBase} w-full px-3 py-2`}
          />
        </Field>
        <Field label={t('market.proposalForm.currency')}>
          <select value={currency} onChange={(e) => setCurrency(e.target.value as 'BRL' | 'USDC')} className={`${inputBase} w-full px-3 py-2`}>
            <option value="BRL">BRL</option>
            <option value="USDC">USDC</option>
          </select>
        </Field>
        <Field label={t('market.proposalForm.accessFrom')}>
          <input type="date" required value={start} onChange={(e) => setStart(e.target.value)} className={`${inputBase} w-full px-3 py-2`} />
        </Field>
        <Field label={t('market.proposalForm.accessUntil')}>
          <input type="date" required value={end} onChange={(e) => setEnd(e.target.value)} className={`${inputBase} w-full px-3 py-2`} />
        </Field>
        <Field label={t('market.proposalForm.note')} className="sm:col-span-2">
          <textarea rows={2} value={note} onChange={(e) => setNote(e.target.value)} className={`${inputBase} w-full px-3 py-2`} />
        </Field>
      </div>
      {error && <p className="text-sm text-red-600 mt-3">{error}</p>}
      <div className="flex flex-col-reverse sm:flex-row sm:justify-end gap-2 mt-4">
        <Button variant="ghost" onClick={onCancel}>{t('common.cancel')}</Button>
        <Button type="submit" variant="accent" disabled={busy}>{busy ? t('market.proposalForm.sending') : t('market.proposalForm.submit')}</Button>
      </div>
    </form>
  );
}
